-- 003_create_claims.sql
-- Creates claims, claim_images, and prevent_self_claim trigger

set search_path = public, extensions;

create table if not exists public.claims (
  id bigint generated by default as identity primary key,
  item_id bigint not null references public.items(id) on delete cascade,
  claimer_id uuid not null references public.users(id) on delete cascade,
  claimer_name text not null check (char_length(claimer_name) between 2 and 100),
  claimer_email text not null,
  claimer_phone text check (claimer_phone is null or char_length(claimer_phone) <= 32),
  description text not null check (char_length(description) between 20 and 1000),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected', 'withdrawn')),
  submitted_at timestamptz not null default now(),
  reviewed_by uuid references public.users(id) on delete set null,
  reviewed_at timestamptz,
  review_notes text check (review_notes is null or char_length(review_notes) <= 1000)
);

create unique index if not exists claims_one_pending_per_user_item
  on public.claims (item_id, claimer_id) where status = 'pending';

create table if not exists public.claim_images (
  id bigint generated by default as identity primary key,
  claim_id bigint not null references public.claims(id) on delete cascade,
  image_url text not null check (image_url like '/api/media/%'),
  description text,
  uploaded_at timestamptz not null default now()
);

create index if not exists claims_item_status_idx on public.claims (item_id, status);
create index if not exists claims_claimer_idx on public.claims (claimer_id, submitted_at desc);

create or replace function public.prevent_self_claim()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  if exists (
    select 1 from public.items
    where id = new.item_id and reported_by = new.claimer_id
  ) then
    raise exception 'An item reporter cannot claim their own item';
  end if;
  return new;
end;
$$;

drop trigger if exists claims_prevent_self_claim on public.claims;
create trigger claims_prevent_self_claim before insert or update of item_id, claimer_id on public.claims
for each row execute function public.prevent_self_claim();

alter table public.claims enable row level security;
alter table public.claim_images enable row level security;

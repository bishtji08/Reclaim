-- 004_create_notifications.sql
-- Creates notifications, audit_logs, matching algorithm, and match notification triggers

set search_path = public, extensions;

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 255),
  message text not null check (char_length(message) between 1 and 2000),
  type text not null check (type in ('match', 'claim', 'system', 'reminder', 'status_update')),
  is_read boolean not null default false,
  related_item_id bigint references public.items(id) on delete cascade,
  related_claim_id bigint references public.claims(id) on delete cascade,
  action_url text,
  created_at timestamptz not null default now(),
  read_at timestamptz
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  user_id uuid references public.users(id) on delete set null,
  action text not null check (char_length(action) <= 100),
  table_name text not null check (char_length(table_name) <= 50),
  record_id text,
  old_values jsonb,
  new_values jsonb,
  ip_address inet,
  user_agent text,
  created_at timestamptz not null default now()
);

create index if not exists notifications_unread_idx on public.notifications (user_id, is_read, created_at desc);
create index if not exists audit_logs_user_idx on public.audit_logs (user_id, created_at desc);

create or replace function public.find_potential_matches(item_id_param bigint)
returns table (
  match_id bigint,
  match_title text,
  match_description text,
  match_score double precision,
  match_reasons text[]
)
language sql
stable
security invoker
set search_path = public
as $$
  select
    candidate.id,
    candidate.title,
    candidate.description,
    (
      case when source.category_id = candidate.category_id then 0.45 else 0 end +
      case when source.color is not null and source.color = candidate.color then 0.25 else 0 end +
      case when source.location_id = candidate.location_id then 0.20 else 0 end +
      case when abs(extract(epoch from (source.reported_at - candidate.reported_at))) < 86400 then 0.10 else 0 end
    )::double precision,
    array_remove(array[
      case when source.category_id = candidate.category_id then 'same category' end,
      case when source.color is not null and source.color = candidate.color then 'same colour' end,
      case when source.location_id = candidate.location_id then 'same location' end
    ], null)
  from public.items source
  join public.items candidate on candidate.id <> source.id
  where source.id = item_id_param
    and source.type <> candidate.type
    and source.status = 'reported'
    and candidate.status = 'reported'
  order by 4 desc, candidate.reported_at desc
  limit 10;
$$;

create or replace function public.notify_potential_matches()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
declare
  match_record record;
begin
  if new.status <> 'reported' or (tg_op = 'UPDATE' and old.status = 'reported') then
    return new;
  end if;

  for match_record in
    select * from public.find_potential_matches(new.id) where match_score >= 0.55
  loop
    insert into public.notifications (user_id, title, message, type, related_item_id)
    select reported_by, 'Potential match found', 'A potentially matching item was reported.', 'match', new.id
    from public.items where id = match_record.match_id;

    insert into public.notifications (user_id, title, message, type, related_item_id)
    values (new.reported_by, 'Potential match found', 'We found a possible match for your report.', 'match', match_record.match_id);
  end loop;

  return new;
end;
$$;

drop trigger if exists items_notify_potential_matches on public.items;
create trigger items_notify_potential_matches after insert or update of status on public.items
for each row execute function public.notify_potential_matches();

alter table public.notifications enable row level security;
alter table public.audit_logs enable row level security;

revoke all on all tables in schema public from anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;

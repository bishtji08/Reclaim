-- 002_create_items.sql
-- Creates categories, subcategories, locations, items, tags, and spatial indexes

set search_path = public, extensions;

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 2 and 100),
  description text,
  icon text,
  created_at timestamptz not null default now(),
  unique (name)
);

create table if not exists public.subcategories (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.categories(id) on delete cascade,
  name text not null check (char_length(name) between 2 and 100),
  description text,
  created_at timestamptz not null default now(),
  unique (category_id, name)
);

create table if not exists public.locations (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 2 and 255),
  description text,
  coordinates geometry(point, 4326),
  building text,
  floor text,
  room text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  unique nulls not distinct (name, building)
);

create table if not exists public.items (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 3 and 255),
  description text not null check (char_length(description) between 3 and 2000),
  type text not null check (type in ('lost', 'found')),
  status text not null default 'reported' check (status in ('reported', 'matched', 'claimed', 'returned', 'closed')),
  category_id bigint not null references public.categories(id) on delete restrict,
  subcategory_id bigint references public.subcategories(id) on delete set null,
  reported_by uuid not null references public.users(id) on delete cascade,
  location_id bigint not null references public.locations(id) on delete restrict,
  specific_location text check (specific_location is null or char_length(specific_location) <= 500),
  coordinates geometry(point, 4326),
  color text check (color is null or char_length(color) <= 50),
  brand text check (brand is null or char_length(brand) <= 100),
  model text check (model is null or char_length(model) <= 100),
  serial_number text check (serial_number is null or char_length(serial_number) <= 100),
  dimensions jsonb,
  estimated_value numeric(10, 2) check (estimated_value is null or estimated_value >= 0),
  is_urgent boolean not null default false,
  reward_offered numeric(10, 2) check (reward_offered is null or reward_offered >= 0),
  date_lost_found date,
  time_lost_found time,
  reported_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  matched_with bigint references public.items(id) on delete set null,
  matched_at timestamptz,
  claimed_by uuid references public.users(id) on delete set null,
  claimed_at timestamptz,
  returned_at timestamptz,
  closed_at timestamptz,
  closure_reason text check (closure_reason is null or char_length(closure_reason) <= 1000),
  check (matched_with is null or matched_with <> id)
);

create table if not exists public.item_images (
  id bigint generated by default as identity primary key,
  item_id bigint not null references public.items(id) on delete cascade,
  image_url text not null check (image_url like '/api/media/%'),
  is_primary boolean not null default false,
  uploaded_at timestamptz not null default now()
);

create unique index if not exists item_images_one_primary_per_item
  on public.item_images (item_id) where is_primary;

create table if not exists public.tags (
  id bigint generated by default as identity primary key,
  name text not null check (name = lower(name) and char_length(name) between 1 and 50),
  created_at timestamptz not null default now(),
  unique (name)
);

create table if not exists public.item_tags (
  item_id bigint not null references public.items(id) on delete cascade,
  tag_id bigint not null references public.tags(id) on delete cascade,
  primary key (item_id, tag_id)
);

create index if not exists items_discovery_idx on public.items (type, status, reported_at desc);
create index if not exists items_category_idx on public.items (category_id);
create index if not exists items_reporter_idx on public.items (reported_by, reported_at desc);
create index if not exists items_location_idx on public.items (location_id);
create index if not exists items_coordinates_idx on public.items using gist (coordinates);
create index if not exists locations_coordinates_idx on public.locations using gist (coordinates);
create index if not exists items_search_idx on public.items using gin (to_tsvector('english', title || ' ' || description));

alter table public.categories enable row level security;
alter table public.subcategories enable row level security;
alter table public.locations enable row level security;
alter table public.items enable row level security;
alter table public.item_images enable row level security;
alter table public.tags enable row level security;
alter table public.item_tags enable row level security;

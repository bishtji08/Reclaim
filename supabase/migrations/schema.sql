-- Automatic user sync from auth.users to public.users
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  user_name text;
  user_role text;
begin
  user_name := coalesce(
    nullif(trim(new.raw_user_meta_data->>'name'), ''),
    nullif(trim(new.raw_user_meta_data->>'full_name'), ''),
    split_part(coalesce(new.email, 'user@example.com'), '@', 1)
  );

  if length(user_name) < 2 then
    user_name := user_name || ' User';
  end if;

  user_role := coalesce(
    case
      when new.raw_app_meta_data->>'role' in ('admin', 'finder', 'user') then new.raw_app_meta_data->>'role'
      else null
    end,
    'user'
  );

  insert into public.users (
    id,
    email,
    name,
    role,
    phone,
    avatar_url,
    is_verified,
    is_active,
    created_at,
    updated_at
  )
  values (
    new.id,
    coalesce(new.email, ''),
    substring(user_name from 1 for 100),
    user_role,
    nullif(trim(new.raw_user_meta_data->>'phone'), ''),
    nullif(trim(new.raw_user_meta_data->>'avatar_url'), ''),
    coalesce(new.email_confirmed_at is not null, false),
    true,
    coalesce(new.created_at, now()),
    coalesce(new.updated_at, now())
  )
  on conflict (id) do update
  set
    email = excluded.email,
    is_verified = coalesce(new.email_confirmed_at is not null, public.users.is_verified),
    updated_at = now();

  return new;
end;
$$;


-- 005_reviews_and_moderation.sql
-- Completes the 14 interrelated database tables for ReClaim
-- Adds public.reviews (feedback), public.item_flags (suspicious item flagging),
-- user blacklisting fields, item suspicious fields, indexes, and RLS policies.

set search_path = public, extensions;

-- 1. Add moderation columns to users
alter table public.users add column if not exists is_blacklisted boolean not null default false;
alter table public.users add column if not exists blacklist_reason text check (blacklist_reason is null or char_length(blacklist_reason) <= 500);
alter table public.users add column if not exists blacklisted_at timestamptz;
alter table public.users add column if not exists blacklisted_by uuid references public.users(id) on delete set null;

create index if not exists users_blacklist_idx on public.users (is_blacklisted) where is_blacklisted;

-- 2. Add moderation columns to items
alter table public.items add column if not exists is_suspicious boolean not null default false;
alter table public.items add column if not exists flag_reason text check (flag_reason is null or char_length(flag_reason) <= 500);

create index if not exists items_suspicious_idx on public.items (is_suspicious) where is_suspicious;

-- 3. Table 13: reviews (Feedback on returned items & claims)
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  item_id bigint not null references public.items(id) on delete cascade,
  claim_id bigint references public.claims(id) on delete set null,
  reviewer_id uuid not null references public.users(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  comment text check (comment is null or char_length(comment) <= 1000),
  was_returned boolean not null default true,
  created_at timestamptz not null default now(),
  unique (item_id, reviewer_id)
);

create index if not exists reviews_item_idx on public.reviews (item_id);
create index if not exists reviews_reviewer_idx on public.reviews (reviewer_id);

-- 4. Table 14: item_flags (Suspicious report moderation workflow)
create table if not exists public.item_flags (
  id bigint generated by default as identity primary key,
  item_id bigint not null references public.items(id) on delete cascade,
  flagged_by uuid not null references public.users(id) on delete cascade,
  reason text not null check (char_length(reason) between 3 and 500),
  status text not null default 'pending' check (status in ('pending', 'reviewed', 'dismissed', 'resolved')),
  admin_notes text check (admin_notes is null or char_length(admin_notes) <= 1000),
  reviewed_by uuid references public.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists item_flags_item_idx on public.item_flags (item_id, status);
create index if not exists item_flags_status_idx on public.item_flags (status, created_at desc);

-- 5. RLS Policies
alter table public.reviews enable row level security;
alter table public.item_flags enable row level security;

-- Reviews can be viewed by all authenticated users
drop policy if exists "Authenticated users can read reviews" on public.reviews;
create policy "Authenticated users can read reviews"
  on public.reviews for select
  using (true);

-- Users can insert reviews for items they reported or claimed
drop policy if exists "Users can submit reviews" on public.reviews;
create policy "Users can submit reviews"
  on public.reviews for insert
  with check (reviewer_id = auth.uid());

-- Flag policies
drop policy if exists "Users can flag items" on public.item_flags;
create policy "Users can flag items"
  on public.item_flags for insert
  with check (flagged_by = auth.uid());

drop policy if exists "Admins can view and manage flags" on public.item_flags;
create policy "Admins can view and manage flags"
  on public.item_flags for all
  using (exists (
    select 1 from public.users where id = auth.uid() and role = 'admin'
  ));
